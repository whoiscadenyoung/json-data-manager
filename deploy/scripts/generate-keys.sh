#!/usr/bin/env bash
# Generate the self-host deployment keys (docs/self-hosting-design.md §4).
# One HS256 JWT_SECRET, from which the anon and service_role API keys are
# minted (HS256 JWTs with a far-future expiry — the classic self-host scheme,
# same claim shape as the CI store job's demo keys). Pure bash + openssl, no
# runtime dependencies beyond POSIX tools.
#
# Usage: deploy/scripts/generate-keys.sh
# Paste the printed block into .env (it overwrites nothing).
set -euo pipefail

JWT_SECRET="$(openssl rand -hex 32)"
EXP=4102444800 # 2100-01-01T00:00:00Z

b64url() {
  openssl base64 -A | tr '+/' '-_' | tr -d '='
}

mint() {
  local role="$1"
  local header payload sig
  header="$(printf '{"alg":"HS256","typ":"JWT"}' | b64url)"
  payload="$(printf '{"iss":"supabase-demo","role":"%s","exp":%s}' "$role" "$EXP" | b64url)"
  sig="$(printf '%s.%s' "$header" "$payload" \
    | openssl dgst -sha256 -hmac "$JWT_SECRET" -binary | b64url)"
  printf '%s.%s.%s' "$header" "$payload" "$sig"
}

ANON_KEY="$(mint anon)"
SERVICE_ROLE_KEY="$(mint service_role)"

cat <<EOF
# Generated by deploy/scripts/generate-keys.sh — $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Paste into .env. Never commit the filled file.
JWT_SECRET=$JWT_SECRET
ANON_KEY=$ANON_KEY
SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
EOF
