/**
 * What goes into the layer-styles sprite (`public/sprites/layer-styles/`),
 * read only by `build.ts`. Icon names are namespaced by family
 * (`shape-*`, `lucide-*`, `maki-*`) so exported styles name their icons
 * unambiguously; uploads are `user-<id>` and never live in this sprite.
 */

function starPath(): string {
  const points: string[] = [];
  for (let index = 0; index < 10; index += 1) {
    const radius = index % 2 === 0 ? 11 : 4.6,
      angle = (Math.PI / 5) * index - Math.PI / 2;
    points.push(
      `${(12 + radius * Math.cos(angle)).toFixed(2)} ${(12.6 + radius * Math.sin(angle)).toFixed(2)}`,
    );
  }
  return `M${points.join("L")}Z`;
}

function svg(body: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">${body}</svg>`;
}

